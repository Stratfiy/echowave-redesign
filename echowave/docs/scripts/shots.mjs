/**
 * Report which `<Screenshot>` slots in the tree still have no image.
 *
 * The slots are declared in the pages, so this script is the only list of
 * outstanding captures — there is no second file to keep in step. Run it after
 * dropping new files into `docs/images/` to see what is left.
 *
 *   node scripts/shots.mjs            # human-readable, exits 0
 *   node scripts/shots.mjs --markdown # regenerate images/SHOTLIST.md
 *   node scripts/shots.mjs --strict   # exit 1 if anything is missing
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const DOCS_ROOT = fileURLToPath(new URL("..", import.meta.url));
const IMAGES_DIR = join(DOCS_ROOT, "images");

const SKIP_DIRS = new Set(["node_modules", "dist", ".astro", "src", "public", "images"]);

/** Every `.mdx` page in the tree, as absolute paths. */
function pages(dir = DOCS_ROOT, found = []) {
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry) || entry.startsWith(".")) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) pages(full, found);
    else if (entry.endsWith(".mdx")) found.push(full);
  }
  return found;
}

/**
 * Pull one attribute out of a `<Screenshot .../>` tag.
 *
 * Deliberately a regex rather than an MDX parse: the tag shape is fixed by the
 * component's own props and a malformed one fails the real build anyway, so a
 * parser here would buy nothing but a dependency.
 */
function attribute(tag, name) {
  const match = tag.match(new RegExp(`\\b${name}\\s*=\\s*"([^"]*)"`, "s"));
  return match ? match[1].replace(/\s+/g, " ").trim() : null;
}

function collect() {
  const have = new Set(readdirSync(IMAGES_DIR));
  const slots = [];

  for (const page of pages()) {
    const body = readFileSync(page, "utf8");
    for (const match of body.matchAll(/<Screenshot\b[^>]*?\/>/gs)) {
      const tag = match[0];
      const src = attribute(tag, "src");
      if (!src) continue;
      slots.push({
        page: relative(DOCS_ROOT, page),
        src,
        alt: attribute(tag, "alt") ?? "",
        caption: attribute(tag, "caption"),
        shot: attribute(tag, "shot"),
        present: have.has(src),
      });
    }
  }

  slots.sort((a, b) => a.page.localeCompare(b.page) || a.src.localeCompare(b.src));
  return slots;
}

function markdown(slots) {
  const missing = slots.filter((slot) => !slot.present);
  const byPage = new Map();
  for (const slot of missing) {
    if (!byPage.has(slot.page)) byPage.set(slot.page, []);
    byPage.get(slot.page).push(slot);
  }

  const lines = [
    "# Screenshots still to capture",
    "",
    "<!-- Generated by `npm run shots -- --markdown`. Do not edit by hand. -->",
    "",
    `${missing.length} of ${slots.length} screenshot slots in the docs have no image yet.`,
    "",
    "Each slot is declared in the page with the filename it expects. Save the",
    "capture into `docs/images/` under exactly that name and it appears — no",
    "page edit, no rebuild config, nothing else to change.",
    "",
    "## How to capture",
    "",
    "- Capture at a **1440px-wide viewport** on a **2x display** so the image is",
    "  crisp when the site scales it down. A 720px-wide screenshot looks soft.",
    "- Use a **real account with realistic data**. An empty state or a workspace",
    "  called `test test` reads as a product nobody uses.",
    "- **Crop to the thing being described.** A full browser window with the OS",
    "  menu bar in it wastes most of the reader's attention on chrome.",
    "- **Redact** phone numbers, API keys, customer names and balances. The names",
    "  used in the docs are Maya, QuickMart and Acme — reuse those.",
    "- Save as **PNG**, under about 400 KB. `pngquant` or `oxipng` if it is over.",
    "",
    "## Outstanding",
    "",
  ];

  for (const [page, entries] of byPage) {
    lines.push(`### \`${page}\``, "");
    for (const slot of entries) {
      lines.push(`- **\`${slot.src}\`** — ${slot.shot || slot.alt}`);
    }
    lines.push("");
  }

  if (missing.length === 0) lines.push("Nothing outstanding. Every slot has an image.", "");

  return lines.join("\n");
}

const slots = collect();
const missing = slots.filter((slot) => !slot.present);

if (process.argv.includes("--markdown")) {
  const out = join(IMAGES_DIR, "SHOTLIST.md");
  writeFileSync(out, markdown(slots));
  console.log(`Wrote ${relative(DOCS_ROOT, out)} — ${missing.length} outstanding.`);
} else {
  for (const slot of slots) {
    console.log(`${slot.present ? "have" : "MISS"}  ${slot.src.padEnd(46)} ${slot.page}`);
  }
  console.log(`\n${slots.length - missing.length}/${slots.length} slots filled.`);
}

if (process.argv.includes("--strict") && missing.length > 0) process.exit(1);
